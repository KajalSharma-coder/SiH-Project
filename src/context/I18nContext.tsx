function readInitialLanguage(): Language {
  const stored = localStorage.getItem(STORAGE_KEY);
  return stored === "hi" || stored === "en" ? stored : "en";
}

if (!i18n.isInitialized) {
  i18n.use(initReactI18next).init({
    resources: {
      en: { translation: en },
      hi: { translation: hi },
    },
    lng: readInitialLanguage(),
    fallbackLng: "en",
    interpolation: { escapeValue: false },
  });
}

const I18nContext = createContext<I18nContextType | undefined>(undefined);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const { t: translate } = useTranslation();
  const language = (i18n.resolvedLanguage === "hi" ? "hi" : "en") as Language;

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<I18nContextType>(() => {
    function t(key: string, values: Record<string, string | number> = {}) {
      return translate(key, values);
    }

    function setLanguage(next: Language) {
      localStorage.setItem(STORAGE_KEY, next);
      void i18n.changeLanguage(next);
    }

    return {
      language,
      setLanguage,
      t,
      roleLabel: (role?: string) => (role ? t(`role.${role}`) : ""),
      statusLabel: (status?: string) => (status ? t(`status.${status}`) : ""),
      paymentLabel: (status?: Deal["paymentStatus"]) => (status ? t(`status.${status}`) : ""),
    };
  }, [language, translate]);

  return (
    <I18nextProvider i18n={i18n}>
      <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
    </I18nextProvider>
  );
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used within an I18nProvider");
  }
  return context;
}
